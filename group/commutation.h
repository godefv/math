	template<class OperatorT, Scalar ScalarT>
	int constexpr sort_index(OperatorT, ScalarT const&){
		if constexpr(std::is_same_v<ScalarT, group::identity_t<OperatorT>>) return 0;
		else if constexpr(SimpleScalar<ScalarT>) return 10;
		else return 20;
	}
	template<class OperatorT, class Name>
	int constexpr sort_index(OperatorT, symbol_t<Name> const&){
		return 30;
	}
	template<class Operator1, class Operator2, class A, class B> requires (!std::is_same<Operator1,Operator2>::value)
	int constexpr sort_index(Operator1, group::generated_by_operation_t<Operator2, A,B> const&){
		return 100;
	}
	template<class OperatorT>
	int constexpr sort_index(OperatorT, auto const&){
		return 200;
	}

	template<class OperatorT, class A>
	auto constexpr sort_as(OperatorT, A const& a){
		return a;
	}
	template<class OperatorT, SimpleScalar ExponentT, class X>
	auto constexpr sort_as(OperatorT op, group::generated_power_t<OperatorT, ExponentT, X> const& pow){
		return sort_as(op, pow.operand);
	}

	template<class OperatorT, class A, class B>
	int constexpr static_compare(OperatorT op, A const& a, B const& b){
		return sort_index(op, b)-sort_index(op, a);
	}
	template<class OperatorT, class T1, class T2>
	requires (!std::is_same<decltype(sort_as(OperatorT{},std::declval<T1>())), T1>::value
	       || !std::is_same<decltype(sort_as(OperatorT{},std::declval<T2>())), T2>::value
	)
	int constexpr static_compare(OperatorT op, T1 const& a, T2 const& b){
		return static_compare(op, sort_as(op, a), sort_as(op, b));
	}

	//name_t
	constexpr int static_compare(auto, name_t<> const&, name_t<> const&){
		return 0;
	}
	template<char C1, char... Name1>
	constexpr int static_compare(auto, name_t<C1,Name1...> const&, name_t<> const&){
		return -1;
	}
	template<char C1, char... Name1>
	constexpr int static_compare(auto, name_t<> const&, name_t<C1,Name1...> const&){
		return 1;
	}
	template<char C1, char... Name1, char C2, char... Name2>
	constexpr int static_compare(auto const& op, name_t<C1,Name1...> const&, name_t<C2,Name2...> const&){
		if constexpr(C1!=C2){
		   return C2-C1;
		}else{
			return static_compare(op, name_t<Name1...>{}, name_t<Name2...>{});
		}
	}

	//T<name_t<...>>
	template<template<class Name> class T, char... Name1, char... Name2>
	int constexpr static_compare(auto const& op, T<name_t<Name1...>> const& a, T<name_t<Name2...>> const& b){
		return static_compare(op, a.name, b.name);
	}

	//powers
	template<class OperatorT, Ratio Exponent1, Ratio Exponent2, class X1, class X2>
	int constexpr static_compare(auto op, group::generated_power_t<OperatorT, Exponent1, X1> const& a, group::generated_power_t<OperatorT, Exponent2, X2> const& b){
		auto operand_order=static_compare(op, a.operand, b.operand);
		if(operand_order!=0){
		   return operand_order;
		}else{
			return (b.exponent-a.exponent).numerator();
		}
	}
	template<class OperatorT, Ratio ExponentT, class X>
	int constexpr static_compare(auto op, group::generated_power_t<OperatorT, ExponentT, X> const& a, auto const& b){
		auto operand_order=static_compare(op, a.operand, b);
		if(operand_order!=0){
		   return operand_order;
		}else{
			return (-a.exponent).numerator();
		}
	}
	template<class A, class OperatorT, Ratio ExponentT, class X> requires (!group::GeneratedPower<A>)
	int constexpr static_compare(auto op, A const& a, group::generated_power_t<OperatorT, ExponentT, X> const& b){
		return -static_compare(op,b,a);
	}

